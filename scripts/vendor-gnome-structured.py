#!/usr/bin/env python3
"""Reproduce notices for the optional native structured-file token readers."""
import argparse
import hashlib
import os
from pathlib import Path
import tomllib


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    repo=Path(__file__).resolve().parents[1]
    packages=tomllib.loads((repo/'native/gnome/Cargo.lock').read_text())['package']
    cache=Path(os.environ.get('CARGO_HOME',Path.home()/'.cargo'))/'registry/src'
    notices=[]
    provenance=['# Native structured-file readers','',
        'Generated by `python3 scripts/vendor-gnome-structured.py` from the independent',
        '`native/gnome/Cargo.lock` and unmodified cached crate license files.',
        'These MIT-licensed Rust readers run on the existing bounded worker lane.',
        'The optional shared-library feature is enabled by the native workspace;',
        'existing desktop/server clients do not enable it. Source spellings and',
        'comments are copied by token range rather than parsed-value serialization.','',
        '| Crate | Version | Cargo package SHA-256 | License file SHA-256 |',
        '|---|---|---|---|']
    for name in ['jsonc-parser','quick-xml']:
        matches=[p for p in packages if p['name']==name]
        if len(matches)!=1:raise RuntimeError('Ambiguous structured dependency: '+name)
        package=matches[0]
        roots=list(cache.glob('*/'+name+'-'+package['version']))
        if len(roots)!=1:raise RuntimeError('Fetch locked GNOME dependencies first: '+name)
        files=sorted(p for p in roots[0].iterdir() if p.is_file() and p.name.startswith(('LICENSE','COPYING','NOTICE')))
        if not files:raise RuntimeError('Missing license: '+name)
        for path in files:
            data=path.read_bytes()
            notices.append('\n===== '+name+' '+package['version']+' / '+path.name+' =====\n\n'+data.decode().replace('\r\n','\n').rstrip()+'\n')
            url='https://crates.io/crates/'+name+'/'+package['version']
            provenance.append('| ['+name+']('+url+') | '+package['version']+' | `'+package['checksum']+'` | '+path.name+': `'+hashlib.sha256(data).hexdigest()+'` |')
    output=repo/'native/gnome/vendor/structured'
    output.mkdir(exist_ok=True)
    for name,value in [('LICENSE',''.join(notices)),('UPSTREAM.md','\n'.join(provenance)+'\n')]:
        path=output/name
        if args.check:
            if not path.is_file() or path.read_text()!=value:raise RuntimeError('Stale structured notice: '+str(path))
        else:path.write_text(value)


if __name__=='__main__':main()
