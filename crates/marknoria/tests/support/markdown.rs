//! Synthetic shared corpus generator. No document or generated fixture is tracked.
pub fn gfm() -> String {
    let lines = [
        "# Public 中文😀 corpus",
        "",
        "First line",
        "Second line with **bold**, *emphasis*, ~~deleted~~ and `literal`.",
        "",
        "- [x] Complete",
        "- [ ] Pending",
        "",
        "Visit https://example.org/a_(b). www.example.org/path, or mail me@example.org.",
        "",
        "[Named](https://target.example.org) and [reference][r].",
        "",
        "> Quoted 中文😀.",
        "",
        "| Name | Value |",
        "| :--- | ---: |",
        "| 中文\\|😀 | 001 |",
        "| https://table.example.org | **2** |",
        "",
        "```python",
        "print('www.code.example.org')",
        "```",
        "",
        "<span onclick=\"forbidden()\">Literal HTML policy</span>",
        "",
        "<script>globalThis.compromised=true</script>",
        "",
        "## Final section",
        "",
        "EOF sentinel 中文😀.",
        "",
        "[r]: https://reference.example.org",
        "",
        "Inline <kbd>Ctrl</kbd> + <strong title=\"literal &amp; title\">HTML bold</strong> and H<sub>2</sub>O.",
        "",
        "<details open><summary>HTML details</summary><p>Safe HTML 中文😀.</p></details>",
        "",
        "<a href=\"https://raw.example.org\" onclick=\"forbidden()\" id=\"source-view\" data-source-line=\"1\">Safe raw link</a>",
    ];
    format!("\u{feff}{}\r\n", lines.join("\r\n"))
}
