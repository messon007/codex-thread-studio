#!/usr/bin/env python3
"""Reproduce the independent native static-HTML sanitizer/tokenizer notices."""
import argparse
import hashlib
import os
from pathlib import Path
import tomllib

PACKAGES = {
    'ammonia':'4.2.4','cssparser':'0.38.0','dtoa':'1.0.11','dtoa-short':'0.3.5',
    'html5ever':'0.40.1','html5gum':'0.8.4','jetscii':'0.5.3','lock_api':'0.4.14',
    'maplit':'1.0.2','markup5ever':'0.40.0','new_debug_unreachable':'1.0.6',
    'parking_lot':'0.12.5','parking_lot_core':'0.9.12','phf':'0.14.0',
    'phf_codegen':'0.14.0','phf_generator':'0.14.0','phf_shared':'0.14.0',
    'precomputed-hash':'0.1.1','redox_syscall':'0.5.18','scopeguard':'1.2.0',
    'string_cache':'0.11.0','string_cache_codegen':'0.11.2','tendril':'0.5.1','web_atoms':'0.3.0',
}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    repo=Path(__file__).resolve().parents[1]
    packages=tomllib.loads((repo/'native/gnome/Cargo.lock').read_text())['package']
    cache=Path(os.environ.get('CARGO_HOME',Path.home()/'.cargo'))/'registry/src'
    licenses=[]
    provenance=['# Native passive HTML Preview','',
        'Generated by `python3 scripts/vendor-gnome-html.py` from the independent',
        '`native/gnome/Cargo.lock` and unmodified cached crate license files.',
        'Ammonia applies HTML5 sanitization on the bounded Rust worker lane.',
        'html5gum supplies source-token spans and preflight budgets, not the security',
        'sanitizer. The native-only graph adds these versions without removing any',
        'previously locked package; the existing desktop/server lockfile is unchanged.',
        'Shared URL and Unicode dependencies retain their existing notices. Platform',
        'and build support is included here even when not a Linux runtime dependency.','',
        '| Crate | Version | License | Cargo package SHA-256 | License file SHA-256 |',
        '|---|---|---|---|---|']
    for name,version in sorted(PACKAGES.items()):
        matches=[p for p in packages if (p['name'],p['version'])==(name,version)]
        if len(matches)!=1:raise RuntimeError('Missing locked HTML dependency: '+name+' '+version)
        package=matches[0]
        roots=list(cache.glob('*/'+name+'-'+version))
        if len(roots)!=1:raise RuntimeError('Fetch locked native dependencies first: '+name)
        metadata=tomllib.loads((roots[0]/'Cargo.toml').read_text())['package']
        files=sorted(p for p in roots[0].iterdir() if p.is_file() and p.name.startswith(('LICENSE','COPYING','NOTICE','COPYRIGHT')))
        if not files:raise RuntimeError('Missing HTML crate notice: '+name)
        for path in files:
            data=path.read_bytes()
            licenses.append('\n===== '+name+' '+version+' / '+path.name+' =====\n\n'+data.decode().replace('\r\n','\n').rstrip()+'\n')
            provenance.append('| ['+name+'](https://crates.io/crates/'+name+'/'+version+') | '+version+' | '+metadata['license']+' | `'+package['checksum']+'` | '+path.name+': `'+hashlib.sha256(data).hexdigest()+'` |')
    output=repo/'native/gnome/vendor/html-preview';output.mkdir(exist_ok=True)
    for name,text in [('LICENSE',''.join(licenses)),('UPSTREAM.md','\n'.join(provenance)+'\n')]:
        path=output/name
        if args.check:
            if not path.is_file() or path.read_text()!=text:raise RuntimeError('Stale native HTML notice: '+str(path))
        else:path.write_text(text)


if __name__=='__main__':main()
