#!/usr/bin/env python3
"""Reproduce notices for the independent GNOME Linux HTTPS transport graph."""
import argparse
import hashlib
import os
from pathlib import Path
import tomllib

PACKAGES = ['foreign-types','foreign-types-shared','hyper-tls','native-tls',
            'openssl','openssl-macros','openssl-probe','openssl-sys',
            'rustls-pki-types','tokio-native-tls','vcpkg','zeroize']


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    repo=Path(__file__).resolve().parent.parent
    packages=tomllib.loads((repo/'native/gnome/Cargo.lock').read_text())['package']
    source=Path(os.environ.get('CARGO_HOME',Path.home()/'.cargo'))/'registry/src'
    licenses=[]
    provenance=['# Native Linux HTTPS transport notices','',
                'Generated by `python3 scripts/vendor-gnome-tls.py` from the independent',
                '`native/gnome/Cargo.lock` and unmodified cached crate license files.',
                'OpenSSL is dynamically linked from Ubuntu; no OpenSSL library or CA store',
                'is bundled. `vcpkg` is build support, not a runtime process. Other-platform',
                'dependency graphs are unchanged. Runtime HTTPS uses system certificate trust.', '',
                '| Crate | Version | Cargo package SHA-256 | License file SHA-256 |',
                '|---|---|---|---|']
    for name in PACKAGES:
        matches=[p for p in packages if p['name']==name]
        if len(matches)!=1:raise RuntimeError('Ambiguous TLS dependency: '+name)
        package=matches[0]
        roots=list(source.glob('*/'+name+'-'+package['version']))
        if len(roots)!=1:raise RuntimeError('Build/fetch locked GNOME dependencies first: '+name)
        notices=sorted(p for p in roots[0].iterdir() if p.name.startswith(('LICENSE','COPYING','NOTICE')) and p.is_file())
        if not notices:raise RuntimeError('Missing crate notice: '+name)
        crate='https://crates.io/crates/'+name+'/'+package['version']
        for path in notices:
            data=path.read_bytes()
            licenses.append('\n===== '+name+' '+package['version']+' / '+path.name+' =====\n\n'+data.decode().replace('\r\n','\n').rstrip()+'\n')
            provenance.append('| ['+name+']('+crate+') | '+package['version']+' | `'+package['checksum']+'` | '+path.name+': `'+hashlib.sha256(data).hexdigest()+'` |')
    output=repo/'native/gnome/vendor/tls'
    output.mkdir(exist_ok=True)
    for name,text in [('LICENSE',''.join(licenses)),('UPSTREAM.md','\n'.join(provenance)+'\n')]:
        dest=output/name
        if args.check:
            if not dest.is_file() or dest.read_text()!=text:raise RuntimeError('Stale TLS notice: '+str(dest))
        else:dest.write_text(text)

if __name__=='__main__':
    main()
